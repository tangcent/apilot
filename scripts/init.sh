#!/bin/bash

set -e

SCRIPT_DIR="$(dirname "$0")"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

SKILLS_SOURCE="$PROJECT_ROOT/.agents/skills"
AGENTS_FILE="$PROJECT_ROOT/AGENTS.md"

# Claude Code needs no initialization: the committed .claude -> .agents
# symlink already exposes .agents/skills as .claude/skills, and CLAUDE.md is a
# symlink to AGENTS.md, so the same rules apply there too.

init_skills_dir() {
    local label="$1"
    local target_dir="$2"

    echo "Initializing $label..."
    if [ ! -d "$SKILLS_SOURCE" ]; then
        echo "✗ No skills found at $SKILLS_SOURCE"
        return 1
    fi
    mkdir -p "$target_dir"
    # Tool directories are generated output. Drop stale skill directories so a
    # skill removed from .agents/skills stops being discovered.
    for stale in "$target_dir"/*/; do
        [ -d "$stale" ] && rm -rf "$stale"
    done
    cp -r "$SKILLS_SOURCE/." "$target_dir/"
    echo "✓ $label skills initialized"
}

# Trae IDE and Kiro do not load a root AGENTS.md by default. Generate a short
# pointer in their native rules directory; AGENTS.md stays the single source.
init_rules_pointer() {
    local label="$1"
    local target_file="$2"
    local always_include="$3"

    if [ ! -f "$AGENTS_FILE" ]; then
        echo "✗ AGENTS.md not found at $AGENTS_FILE"
        return 1
    fi
    mkdir -p "$(dirname "$target_file")"
    {
        if [ -n "$always_include" ]; then
            printf '%s\n' '---' 'inclusion: always' '---' ''
        fi
        cat <<'EOF'
# Project instructions

Read `AGENTS.md` at the repository root before starting any work. It is the
single source of truth for project constraints and indexes all detailed
references. Generated by `scripts/init.sh` — do not edit by hand.
EOF
    } > "$target_file"
    echo "✓ $label rules pointer initialized"
}

init_trae() {
    init_skills_dir "Trae" "$PROJECT_ROOT/.trae/skills"
    init_rules_pointer "Trae" "$PROJECT_ROOT/.trae/rules/project-instructions.md" ""
}

init_qoder() {
    init_skills_dir "Qoder" "$PROJECT_ROOT/.qoder/skills"
}

init_workbuddy() {
    init_skills_dir "WorkBuddy" "$PROJECT_ROOT/.workbuddy/skills"
}

init_kiro() {
    init_skills_dir "Kiro" "$PROJECT_ROOT/.kiro/skills"
    init_rules_pointer "Kiro" "$PROJECT_ROOT/.kiro/steering/project-instructions.md" "always"
}

init_cursor() {
    init_skills_dir "Cursor" "$PROJECT_ROOT/.cursor/skills"
}

show_help() {
    echo "Usage: $0 [OPTIONS]"
    echo ""
    echo "Initialize AI tools with skills from .agents/skills"
    echo "AGENTS.md is the shared rule source; tool-specific pointers are generated."
    echo "Claude Code needs no setup: .claude -> .agents and CLAUDE.md -> AGENTS.md are symlinks."
    echo ""
    echo "Options:"
    echo "  --all         Initialize all AI tools (default)"
    echo "  --trae        Initialize Trae only"
    echo "  --qoder       Initialize Qoder only"
    echo "  --workbuddy   Initialize WorkBuddy only"
    echo "  --kiro        Initialize Kiro only"
    echo "  --cursor      Initialize Cursor only"
    echo "  --help        Show this help message"
    echo ""
    echo "Examples:"
    echo "  $0              # Initialize all tools"
    echo "  $0 --all        # Initialize all tools"
    echo "  $0 --qoder      # Initialize Qoder only"
}

initialize_all() {
    init_trae
    init_qoder
    init_workbuddy
    init_kiro
    init_cursor
    echo ""
    echo "All AI tools initialized successfully!"
}

if [ $# -eq 0 ]; then
    initialize_all
else
    while [ $# -gt 0 ]; do
        case "$1" in
            --all)
                initialize_all
                shift
                ;;
            --trae)
                init_trae
                shift
                ;;
            --qoder)
                init_qoder
                shift
                ;;
            --workbuddy)
                init_workbuddy
                shift
                ;;
            --kiro)
                init_kiro
                shift
                ;;
            --cursor)
                init_cursor
                shift
                ;;
            --help|-h)
                show_help
                exit 0
                ;;
            *)
                echo "Unknown option: $1"
                show_help
                exit 1
                ;;
        esac
    done
fi
